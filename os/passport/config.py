"""PassportOS 硬件事实 —— 唯一事实来源。

数值全部来自 FoloToy 官方 BSP：
    components/bsp/include/bsp_pins.h   （引脚 / 电阻梯电压窗口）
    components/bsp/src/bsp_display.c    （ST7789P3 厂商初始化序列）
    components/bsp/src/bsp_battery.c    （CW2017 寄存器）
换板只改这一个文件。
"""

# ===========================================================================
# 显示：ST7789P3  240x320  4线 SPI
# ===========================================================================
LCD_W = 240
LCD_H = 320
LCD_SPI_ID = 1          # MicroPython 侧自选；IDF 里是 SPI2_HOST
LCD_MOSI = 9
LCD_SCLK = 8
LCD_CS = 1
LCD_DC = 20
LCD_RST = -1            # 复位脚未接 MCU（硬接 3.3V），只能走 SWRESET 软复位
LCD_BL = 21             # 背光，LEDC PWM 调光
LCD_BAUD = 40_000_000   # SCK 空闲低、上升沿采样 → SPI mode 0
LCD_SPI_MODE = 0
LCD_INVERT = True       # 本屏出厂即需反色（参考例程无条件发 0x21 INVON）
LCD_BL_FREQ = 5000

# ===========================================================================
# 三键电阻梯：3.3V ──10k 上拉──┬── ADC(GPIO0) └── 按键 ──分压── GND
#   上  0Ω   ≈   0 mV
#   下  1k   ≈ 300 mV
#   确定 2.2k ≈ 595 mV
#   松开      ≈3300 mV
# 窗口边界取相邻档中点。⚠ 绝不能改用内部上拉（约 45kΩ，会把三档挤到一起）。
# ===========================================================================
BTN_ADC_PIN = 0
BTN_WINDOWS = (
    ("up",   0,  150),
    ("down", 150, 447),
    ("ok",   447, 1900),
)
BTN_RELEASED_MV = 1900   # 高于此值判定为松开

# ===========================================================================
# I2C：ES8311(音频 codec) 与 CW2017(电量计) 共用一条总线
# ===========================================================================
I2C_SDA = 10
I2C_SCL = 7
I2C_FREQ = 400_000
ADDR_ES8311 = 0x18      # 7 位地址
ADDR_CW2017 = 0x63

# CW2017 寄存器
CW_REG_VERSION = 0x00
CW_REG_VCELL_H = 0x02   # 14bit，V(uV) = raw * 312.5
CW_REG_SOC_H = 0x04     # 高字节 = 整数百分比

# ===========================================================================
# 音频：ES8311，I2S 播放已实现（录音未实现）
# 接口与用法见 docs/ble-protocol.md 的「ctx.audio 音频接口」
# ===========================================================================
I2S_MCLK = 6
I2S_BCLK = 5
I2S_WS = 3
I2S_DOUT = 2            # 播放：MCU → codec
I2S_DIN = 4             # 录音：codec → MCU

# ===========================================================================
# 蓝牙 GATT：PassportOS 小程序推送协议
#   末 12 位 "70617373706f" = ASCII "passpo"，便于肉眼识别
# ===========================================================================
BLE_NAME = "PassportOS"
UUID_SERVICE = "7a5c0001-0000-4000-8000-70617373706f"
UUID_CMD = "7a5c0002-0000-4000-8000-70617373706f"   # 手机 → 设备（写）
UUID_RSP = "7a5c0003-0000-4000-8000-70617373706f"   # 设备 → 手机（通知）
BLE_MTU = 247
# CMD 特征值的最大长度。MicroPython 默认只给 20 字节，超过就被静默截断，
# 所以必须用 gatts_set_buffer() 显式放大。
BLE_ATTR_MAX_LEN = 2048

# 连接空闲看门狗。
# 为什么需要：如果中心设备（手机/电脑）异常消失而没有发正常的断开，
# 有些主机（实测 Windows）会把 BLE 链路一直挂着。设备就永远停在"已连接"，
# 不再广播 —— 表现就是"浏览器再也扫不到设备"，只能重启设备。
# 所以：连接期间超过这个时间没收到任何写入，就主动断开并恢复广播。
# App/CLI 会每 20~30 秒发一次 ping 续命，所以正常会话不会被误杀。
# 设为 0 关闭这个功能。
# 实测 Windows：客户端 disconnect() 之后主机仍会抓着链路不放，设备收不到断开
# 事件；而连接失败的超时尝试也会留下悬空链路。所以这个值不要设太大，
# 否则设备会长时间不广播、看起来像"坏掉了"。
BLE_IDLE_TIMEOUT_MS = 25000

# ===========================================================================
# 小程序存储
# ===========================================================================
APPS_DIR = "/apps"
MAX_APP_SIZE = 32 * 1024        # 单个小程序上限 32KB
MAX_APPS = 12

# 打开后会把每一次 BLE 写入的原始字节打到串口。排障用，平时关掉
# （上传小程序时每 160 字节一条，开着会很吵）。
DEBUG_BLE = False
